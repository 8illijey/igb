/**
 * 레시피 제목 → URL 슬러그.
 *
 * 앱과 빌드 스크립트(scripts/gen-seo.mjs)가 **같은 함수**를 써야 한다.
 * 규칙을 양쪽에 베껴 쓰면 언젠가 어긋나서, 사이트맵의 주소와 앱이 만드는 주소가
 * 달라진다(2026-08-20 kamis 이름 규칙에서 실제로 겪었다).
 * 그래서 의존성이 하나도 없는 파일로 떼어 둔다 — Node가 타입 스트리핑만으로 불러온다.
 *
 * 왜 순번이 아니라 제목인가:
 *   레시피 목록은 워커가 주1회 갱신하며 순서가 바뀐다. /recipe/0은 이번 주와
 *   다음 주가 다른 글을 가리켜, 검색엔진이 색인한 내용과 실제가 어긋난다.
 *
 * 한글을 그대로 둔다 — 국내 검색에서 주소에 제목이 보이는 편이 유리하고,
 * 브라우저·서버가 알아서 퍼센트 인코딩한다.
 */
export function recipeSlug(title: string): string {
  return String(title)
    .trim()
    .replace(/[/?#&%\s]+/g, '-') // 경로·쿼리에서 의미를 갖는 문자와 공백
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}
